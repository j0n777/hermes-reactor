export const MESSAGES = { en, 'pt-BR': ptBR }

/** Map any locale-ish value to a supported locale id, or null. */
export function normalizeLocale(value) {
  if (typeof value !== 'string') return null
  const lower = value.trim().toLowerCase().replace(/_/g, '-')
  if (!lower) return null
  if (lower === 'pt' || lower.startsWith('pt-')) return 'pt-BR'
  if (lower === 'en' || lower.startsWith('en-')) return 'en'
  return null
}

/**
 * Pick the UI locale.
 * - `preference`: 'auto' | 'en' | 'pt-BR' (the user's explicit choice in this plugin).
 * - `appLocale`: the Hermes Desktop locale (display.language).
 * - `navigatorLanguages`: used only when Hermes reports plain English or nothing and the
 *   user did not choose, because Hermes has no Portuguese pack and English is its default.
 */
export function resolveLocale({ preference = 'auto', appLocale = null, navigatorLanguages = [] } = {}) {
  if (preference === 'en' || preference === 'pt-BR') return preference
  const app = normalizeLocale(appLocale)
  if (app === 'pt-BR') return 'pt-BR'
  const appRaw = typeof appLocale === 'string' ? appLocale.trim().toLowerCase() : ''
  const appIsPlainEnglish = !appRaw || appRaw === 'en' || appRaw.startsWith('en-')
  if (appIsPlainEnglish) {
    for (const lang of navigatorLanguages || []) {
      const n = normalizeLocale(lang)
      if (n === 'pt-BR') return 'pt-BR'
      if (n === 'en') break
    }
  }
  return 'en'
}

function format(template, params) {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, name) => (Object.hasOwn(params, name) ? String(params[name]) : whole))
}

/** Build a translator. Missing key in the locale falls back to English, then to the key. */
export function makeT(locale) {
  const table = ownGet(MESSAGES, locale) || MESSAGES.en
  return function t(key, params) {
    const template = ownGet(table, key) ?? ownGet(MESSAGES.en, key) ?? key
    return format(template, params)
  }
}
