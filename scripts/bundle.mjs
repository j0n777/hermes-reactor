// Shared by the build script and the tests: bundle src/ into one ESM string, and check the
// result against the same rules `hermes plugins validate` applies to a Desktop surface
// (hermes_cli/plugin_validate_desktop.py, rule 8) plus the loader's import allowlist.

import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUTFILE = path.join(root, 'desktop', 'plugin.js')
export const EXTERNAL = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime']

const BANNER = '// Generated by scripts/build.mjs from src/. Do not edit by hand: run `npm run build`.'

export async function bundle() {
  const result = await build({
    entryPoints: [path.join(root, 'src', 'index.js')],
    absWorkingDir: root,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    external: EXTERNAL,
    minify: false,
    legalComments: 'none',
    charset: 'ascii',
    treeShaking: true,
    logLevel: 'silent',
    write: false,
    outfile: OUTFILE,
    banner: { js: BANNER }
  })
  const text = result.outputFiles[0].text.replace(/\r\n/g, '\n')
  return text.endsWith('\n') ? text : text + '\n'
}

// ---- the same tripwires the validator and the Desktop loader use ----

const FORBIDDEN = [
  ['dynamic code evaluation', /(?<![\w$.])eval\(|\bnew\s+Function\(/],
  ['dynamic import', /\bimport\(/],
  ['remote import', /\bimport\s+(?:[^;'"]*?\bfrom\s*)?['"][a-zA-Z][\w+.-]*:/],
  ['script injection', /createElement\(\s*['"]script['"]\s*\)|<script\b/],
  ['app DOM reach', /\bdocument\.(?:querySelector(?:All)?|getElementsBy\w+|getElementById)\(\s*[`'"][^`'"]*\[data-(?:slot|tour|sidebar|testid)\b/],
  ['app DOM reach (observer)', /\.observe\(\s*document\.body\s*,\s*\{[^}]*\b(?:childList|subtree)\b/],
  ['preview guest reach', /\b(?:querySelector(?:All)?|closest|getElementsByTagName|createElement)\(\s*[`'"]webview\b/],
  ['raw bridge', /\b(?:window|globalThis|self)\s*(?:\?\.|\.)\s*hermesDesktop\b/],
  ['app markup selector', /\[data-(?:slot|tour|sidebar|testid|tree-[\w-]+|pane-host|titlebar-cluster)\b/],
  ['network call', /\b(?:fetch|XMLHttpRequest|WebSocket|EventSource|sendBeacon)\b/],
  ['prototype patching', /\.prototype\.\w+\s*=[^=]/]
]

const ALLOWED_IMPORTS = new Set(EXTERNAL)

/** @returns {string[]} human-readable problems; empty when the bundle is clean */
export function lintBundle(source) {
  const problems = []
  const lines = source.split('\n')
  lines.forEach((line, index) => {
    const trimmed = line.trim()
    if (trimmed.startsWith('//')) return
    for (const [rule, pattern] of FORBIDDEN) {
      if (pattern.test(line)) problems.push(`${rule} (line ${index + 1}): ${trimmed.slice(0, 100)}`)
    }
  })
  for (const m of source.matchAll(/^\s*import\s[^;]*?from\s*(['"])([^'"]+)\1/gm)) {
    if (!ALLOWED_IMPORTS.has(m[2])) problems.push(`import outside the SDK: ${m[2]}`)
  }
  for (const m of source.matchAll(/^\s*import\s*(['"])([^'"]+)\1/gm)) {
    problems.push(`side-effect import: ${m[2]}`)
  }
  if (!/export\s+default\b|export\s*\{[^}]*\bas\s+default\b/.test(source)) problems.push('no default export')
  return problems
}
